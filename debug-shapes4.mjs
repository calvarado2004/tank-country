import { chromium } from 'playwright';
const browser = await chromium.launch({ headless: true, executablePath: process.env.HOME + '/Library/Caches/ms-playwright/chromium-1223/chrome-mac-arm64/Google Chrome for Testing.app/Contents/MacOS/Google Chrome for Testing' });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
page.on('pageerror', err => console.log('PAGEERROR', err.stack));
await page.goto('http://localhost:5173/', { waitUntil: 'networkidle' });
await page.waitForTimeout(1000);
await page.click('#btn-deploy');
await page.waitForTimeout(3000);
await page.addStyleTag({ content: '* { backdrop-filter: none !important; -webkit-backdrop-filter: none !important; }' });
await page.waitForTimeout(500);
await page.screenshot({ path: '/tmp/tank-nobackdrop.png' });
await page.addStyleTag({ content: '.status-panel, .map-panel, .mission-id, .objectives-strip, .wave-readout, .toast { box-shadow: none !important; }' });
await page.waitForTimeout(400);
await page.screenshot({ path: '/tmp/tank-noshadowui.png' });
await browser.close();
